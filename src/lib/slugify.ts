/**
 * Turn a (Vietnamese) title or tag into a URL-safe slug:
 * "Học AI: ngày đầu tiên" → "hoc-ai-ngay-dau-tien".
 */
export function slugify(text: string): string {
  return text
    .toLowerCase()
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .replace(/đ/g, "d")
    .replace(/[^a-z0-9\s-]/g, "")
    .trim()
    .replace(/\s+/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "");
}
